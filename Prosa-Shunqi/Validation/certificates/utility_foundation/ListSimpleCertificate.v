(** Canonical order- and multiplicity-preserving map from the MathComp
    sequence carrier to the exact monomorphic [List Nat] carrier generated by
    lean4export for the compiled Prosa.Util.List artifact. *)
Fixpoint list_simple_to_imported (xs : seq nat) :
    ImportedListSimple.List_inst1 Lean.Nat :=
  match xs with
  | [::] => ImportedListSimple.List_nil_inst1 Lean.Nat
  | x :: xs' => ImportedListSimple.List_cons_inst1 Lean.Nat
      (sub_nat_to_imported x) (list_simple_to_imported xs')
  end.

Lemma list_simple_foldl_nil {A B : Type} (f : A -> B -> A) (z : A) :
  Lean.eq
    (ImportedListSimple.List_foldl_inst3 A B f z
      (ImportedListSimple.List_nil_inst1 B)) z.
Proof. exact (@Lean.eq_refl A z). Qed.

Lemma list_simple_foldl_cons {A B : Type} (f : A -> B -> A)
    (z : A) (x : B) (xs : ImportedListSimple.List_inst1 B) :
  Lean.eq
    (ImportedListSimple.List_foldl_inst3 A B f z
      (ImportedListSimple.List_cons_inst1 B x xs))
    (ImportedListSimple.List_foldl_inst3 A B f (f z x) xs).
Proof. exact (@Lean.eq_refl A
  (ImportedListSimple.List_foldl_inst3 A B f (f z x) xs)). Qed.

